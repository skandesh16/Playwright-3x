// Increment Opereator

// 1 Pre Increment -> ++a; 
// 2 Post Increment -> a++;

// Decrement Opereator

// 1 Pre Decrement -> --a;
// 2 Post Decrement -> a--;

//  Increment 
a = 10;
a = a+1;
console.log(a); //11

// Decrement 
a = 10;
a = a-1;
console.log(a); //9

// Pre Increment 
a = 16;
b = ++a;
console.log(a);





