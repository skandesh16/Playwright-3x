// +, -, * , /, %, ** 

// modulus  % - Gives the Remainder value
console.log(14 % 7);

// Power of a and b - Gives the value of a raised to the power of b


let a = 10;
let b = 3;
sum = a + b;
difference = a - b;
product = a * b;
division = a / b;
modulus = a % b;
power = a ** b;

console.log("Sum of a and b is: " + sum);
console.log("Difference of a and b is: " + difference);
console.log("Product of a and b is: " + product);
console.log("Division of a and b is: " + division);
console.log("Modulus of a and b is: " + modulus);
console.log("Power of a and b is: " + power);

