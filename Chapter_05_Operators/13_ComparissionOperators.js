// Comparission Operator (Will always return in Boolean True or False)

// =, ==, ===

// = -> Assignment Operator

// == -> Comparison Operator (Strictly checks value)

// === -> Strict Comparison Operator (Checks value and data type)

// Exaample
// == Loose comparison

// console.log(5 == '5'); // True

// // === Strict comparison

// console.log(5 === '5'); // False

// // != Loose Comparison

// console.log(5 != '5'); // False

// // !== Strict Comparison

// console.log(5 !== '5'); // True

//====================================================

console.log(4 == '4');
console.log(5 != '5');